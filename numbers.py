# Integer, float, complex
a = 5           # Integer
b = 5.5         # Float
c = 3 + 4j      # Complex
print(type(a))
print(type(b))
print(type(c))

a = int(3.45)
b = float(5)
c = complex(3)
print(a, b, c)

# add, sub, mul, div, floor div, modulo, exponentiation
# add +
# sub -
# mul *
# div /
# floor div //
# modulo %
# exponentiation **
print(5 + 2)
print(5 - 2)
print(5 * 2)
print(5 / 2)
print(5 // 2)
print(5 % 2)
print(5 ** 2)

print(abs(-5))
print(pow(5,2))
print(round(3.75))
print(round(3.45))
print(divmod(5,2))
print(max(5,2))
print(min(5,2))
